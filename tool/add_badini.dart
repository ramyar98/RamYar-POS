String _escape(String s) {
  final b = StringBuffer();
  for (final ch in s.split('')) {
    if (ch == r'\') {
      b.write(r'\\');
    } else if (ch == r"'") {
      b.write(r"\'");
    } else if (ch == r'$') {
      b.write(r'\$');
    } else {
      b.write(ch);
    }
  }
  return b.toString();
}

void main() {
  const path = 'lib/services/app_localizations.dart';
  final lines = File(path).readAsLinesSync();
  final out = <String>[];
  var inserted = 0;
  var skipped = 0;
  var curatedUsed = 0;

  var i = 0;
  while (i < lines.length) {
    final line = lines[i];
    out.add(line);
    final m = RegExp(r"^  '([^']*)': \{$").firstMatch(line);
    if (m != null) {
      final key = m.group(1)!;
      // Scan the map body for an existing badini entry.
      var j = i + 1;
      var hasBadini = false;
      while (j < lines.length && !RegExp(r'^  \},$').hasMatch(lines[j])) {
        if (lines[j].contains('AppLanguage.badini:')) {
          hasBadini = true;
          break;
        }
        j++;
      }
      if (hasBadini) {
        skipped++;
      } else {
        if (_curated.containsKey(key)) {
          curatedUsed++;
        }
        final value = _curated[key] ?? key;
        out.add("    AppLanguage.badini: '${_escape(value)}',");
        inserted++;
      }
    }
    i++;
  }

  File(path).writeAsStringSync(out.join('\n'));
  stdout.writeln('inserted=$inserted skipped=$skipped curated=$curatedUsed');
  final curatedNotFound = _curated.keys
      .where((k) => !out.any((l) => l.startsWith("  '$k': {")))
      .toList();
  if (curatedNotFound.isNotEmpty) {
    stdout.writeln('curated keys NOT found in file (${curatedNotFound.length}):');
    for (final k in curatedNotFound) {
      stdout.writeln('  - $k');
    }
    exitCode = 2;
  } else {
    stdout.writeln('all ${_curated.length} curated keys matched');
  }
}